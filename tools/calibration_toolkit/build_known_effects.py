#!/usr/bin/env python3
"""Build data/known_effects.json: a snapshot of what the calibration-map research has
traced about each calibration's on-device behaviour, plus this toolkit's own
predicted/untested notes.

Inputs (read only):
  <repo>/research/calibration-map/map.json   per-row status, values and rule ids
  <repo>/research/calibration-map/rules.py   each rule's feature, effect, level, note
  predicted_effects.json (beside this script) hand-maintained predictions

    python3 build_known_effects.py /path/to/gminfo_resources           # rewrite the snapshot
    python3 build_known_effects.py /path/to/gminfo_resources --check   # report drift, exit 1

sync_bundle.py calls build() too, so the usual bundle refresh and --check cover this file.

Nothing is invented here. A row enters the snapshot only if map.json attaches a rule or a
value effect to it, or predicted_effects.json names it. Statuses, effect text and levels
are copied verbatim; a prediction never changes a row's map status.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import runpy
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAP_DIR = "research/calibration-map"
OUT = Path("data/known_effects.json")
PREDICTED = HERE / "predicted_effects.json"
PREDICTED_EVIDENCE = "predicted, untested"
RULE_FIELDS = ("feature", "expr", "effect", "level", "check", "note")
ROW_FIELDS = ("status", "basis", "caldef", "image", "bench", "bench_slot", "bench_part")


def _fail(msg: str):
    sys.exit(f"error: {msg}")


def build(repo: Path) -> bytes:
    src = repo / MAP_DIR
    map_bytes = (src / "map.json").read_bytes()
    rules_bytes = (src / "rules.py").read_bytes()
    cmap = json.loads(map_bytes)
    rules_mod = runpy.run_path(str(src / "rules.py"))
    rules = {r["id"]: r for r in rules_mod["RULES"]}
    statuses = cmap["statuses"]

    # map.json carries its own copy of each rule; if it disagrees with rules.py the map
    # is stale and the row -> rule attachments cannot be trusted.
    for r in cmap["rules"]:
        mine = rules.get(r["id"])
        if mine is None or any(mine[f] != r[f] for f in RULE_FIELDS):
            _fail(f"rule {r['id']!r} differs between map.json and rules.py -- rerun build_map.py first")

    pred_doc = json.loads(PREDICTED.read_text(encoding="utf-8"))
    if pred_doc["evidence"] != PREDICTED_EVIDENCE:
        _fail(f"predicted_effects.json must keep evidence {PREDICTED_EVIDENCE!r}")
    predictions = pred_doc["predictions"]

    rows = cmap["settings"]
    entries, used_rules = {}, set()
    for name in sorted(rows):
        row = rows[name]
        if row["status"] not in statuses:
            _fail(f"{name}: unknown status {row['status']!r}")
        if not (row["rules"] or row["value_effect"] or name in predictions):
            continue
        for rid in row["rules"]:
            if rid not in rules:
                _fail(f"{name}: rule {rid!r} is not in rules.py")
        used_rules.update(row["rules"])
        entry = {f: row[f] for f in ROW_FIELDS}
        entry["rules"] = list(row["rules"])
        entry["value_effect"] = row["value_effect"]
        if name in predictions:
            p = predictions[name]
            for rid in p["see_map_rules"]:
                if rid not in row["rules"]:
                    _fail(f"{name}: prediction cites rule {rid!r}, which map.json does not attach to it")
            entry["predicted"] = {"evidence": PREDICTED_EVIDENCE, "source": pred_doc["source"], **p}
        entries[name] = entry
    missing = sorted(set(predictions) - set(entries))
    if missing:
        _fail(f"predicted_effects.json names rows that are not in map.json: {missing}")

    counts: dict[str, int] = {}
    for row in rows.values():
        counts[row["status"]] = counts.get(row["status"], 0) + 1
    doc = {
        "_about": "Generated by build_known_effects.py -- do not edit by hand. Reverse-engineered "
                  "findings from research/calibration-map, not GM's CalDef text. Rows of the map "
                  "with no rule, value effect or prediction are deliberately absent: nothing is "
                  "known about what they do.",
        "source": {
            "map": f"{MAP_DIR}/map.json",
            "rules": f"{MAP_DIR}/rules.py",
            "firmware": cmap["firmware"],
            "map_sha256": hashlib.sha256(map_bytes).hexdigest(),
            "rules_sha256": hashlib.sha256(rules_bytes).hexdigest(),
            "map_rows": len(rows),
            "map_status_counts": {s: counts.get(s, 0) for s in statuses},
        },
        "evidence": {
            "statuses": statuses,
            "rule_levels": {
                "traced": "code connects the setting to the effect",
                "observed": "a saved log or owner record shows it",
            },
            "predicted": f"{PREDICTED_EVIDENCE}: reasoned from code reading in one chat session; "
                         "not part of the calibration map and not run on hardware",
        },
        "rules": {rid: {f: rules[rid][f] for f in RULE_FIELDS} for rid in sorted(used_rules)},
        "entries": entries,
    }
    return (json.dumps(doc, indent=1, ensure_ascii=False) + "\n").encode("utf-8")


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("repo", type=Path)
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    want = build(args.repo.resolve())
    path = HERE / OUT
    same = path.is_file() and path.read_bytes() == want
    if args.check:
        print(f"{OUT}: {'up to date' if same else 'differs or missing'}")
        sys.exit(0 if same else 1)
    if not same:
        path.write_bytes(want)
    n = len(json.loads(want)["entries"])
    print(f"{'unchanged' if same else 'wrote'} {OUT}: {n} entries")


if __name__ == "__main__":
    main()
