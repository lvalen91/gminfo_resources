import socket
import struct
import unittest

from mdi2.capture_read_transport import CaptureReadTransport, TransportError, _cop, _frame


class FakeSocket:
    def __init__(self, incoming=b"", *, fail_send=False):
        self.incoming = bytearray(incoming)
        self.sent = []
        self.closed = False
        self.fail_send = fail_send

    def settimeout(self, value):
        self.timeout = value

    def sendall(self, data):
        if self.fail_send:
            raise socket.timeout("not persisted")
        self.sent.append(data)

    def recv(self, size):
        if not self.incoming:
            raise socket.timeout("not persisted")
        # Exercise fragmented socket reads.
        count = min(size, len(self.incoming), 7)
        out = self.incoming[:count]
        del self.incoming[:count]
        return bytes(out)

    def close(self):
        self.closed = True


def event(uds):
    payload = bytearray(82 + len(uds))
    struct.pack_into("<I", payload, 0, 1)
    struct.pack_into("<I", payload, 4, 1)
    struct.pack_into("<H", payload, 20, 5)
    payload[70:74] = (0x123).to_bytes(4, "big")
    struct.pack_into("<I", payload, 74, 4 + len(uds))
    payload[78:82] = (0x123).to_bytes(4, "big")
    payload[82:] = uds
    return _frame(0x863, payload)


class ReadTransportTests(unittest.TestCase):
    def make_transport(self, events=b"", ack_count=2, fail_send=False):
        ack = _frame(0x464, bytes(4))
        cmd = FakeSocket(ack * ack_count, fail_send=fail_send)
        evt = FakeSocket(events)
        adapter = CaptureReadTransport(cmd, evt, radio_handle=1, receive_cop=5, first_free_cop=6,
                                       request_can_id=0x456, response_can_id=0x123,
                                       keepalive_handle=2, functional_can_id=0x789)
        return adapter, cmd, evt

    def test_keepalive_read_pending_then_response(self):
        adapter, cmd, _ = self.make_transport(event(b"\x7f\x22\x78") +
                                               event(b"\x62\xf1\x82\x01"))
        adapter.start_keepalive()
        adapter.send(b"\x22\xf1\x82")
        self.assertEqual(adapter.receive(1), b"\x7f\x22\x78")
        self.assertEqual(adapter.receive(1), b"\x62\xf1\x82\x01")
        self.assertEqual(len(cmd.sent), 2)
        with self.assertRaises(ValueError):
            adapter.send(b"\x22\xf1\x82")

    def test_rejects_programming_without_any_send(self):
        adapter, cmd, _ = self.make_transport(ack_count=1)
        adapter.start_keepalive()
        for req in (b"\x34\x00", b"\x36\x01", b"\x37", b"\x10\x02",
                    b"\x27\x01", b"\x31\x01\x02\x49", b"\x11\x01"):
            with self.subTest(req=req), self.assertRaises(ValueError):
                adapter.send(req)
        self.assertEqual(len(cmd.sent), 1)

    def test_wrong_did_poisons_both_sockets(self):
        adapter, cmd, evt = self.make_transport(event(b"\x62\xf1\x90\x01"))
        adapter.start_keepalive()
        adapter.send(b"\x22\xf1\x82")
        with self.assertRaises(TransportError):
            adapter.receive(1)
        self.assertTrue(cmd.closed and evt.closed)
        with self.assertRaises(TransportError):
            adapter.send(b"\x22\xf0\xf0")

    def test_partial_event_timeout_poisoned(self):
        adapter, cmd, evt = self.make_transport(event(b"\x62\xf1\x82")[:20])
        adapter.start_keepalive()
        adapter.send(b"\x22\xf1\x82")
        with self.assertRaises(TransportError):
            adapter.receive(1)
        self.assertTrue(cmd.closed and evt.closed)

    def test_command_timeout_is_ambiguous_and_closes(self):
        adapter, cmd, evt = self.make_transport(fail_send=True)
        with self.assertRaisesRegex(TransportError, "ambiguous"):
            adapter.start_keepalive()
        self.assertTrue(cmd.closed and evt.closed)
        self.assertEqual(adapter.keepalive_cop, 6)

    def test_negative_response_ends_session(self):
        adapter, cmd, evt = self.make_transport(event(b"\x7f\x22\x31"))
        adapter.start_keepalive()
        adapter.send(b"\x22\xf1\x82")
        with self.assertRaisesRegex(TransportError, "NRC 31"):
            adapter.receive(1)
        self.assertTrue(cmd.closed and evt.closed)

    def test_prequeued_matching_event_cannot_prove_freshness(self):
        # This deliberately demonstrates the unresolved stale-event ambiguity.
        # The matching response is queued before send(), yet the decoder cannot
        # distinguish it from a response generated by the current request.
        adapter, _, _ = self.make_transport(event(b"\x62\xf1\x82\x01"))
        adapter.start_keepalive()
        adapter.send(b"\x22\xf1\x82")
        self.assertEqual(adapter.receive(1), b"\x62\xf1\x82\x01")

    def test_frame_constructor_changes_only_payload_and_id_fields(self):
        # Vehicle-tested channel 0x25: marker 0x2510, byte-identical to pre-fix.
        primitive = _cop(0x25000001, 6, (0x456).to_bytes(4, "big") + b"\x22\xf1\x82")
        self.assertEqual(struct.unpack_from("<IHHHHI", primitive),
                         (0x25000001, 6, 0x2510, 0x8004, 0, 7))
        self.assertEqual(primitive[16:23], bytes.fromhex("0000045622f182"))

    def test_frame_marker_derives_from_channel(self):
        # The 0x463 marker is (channel << 8) | 0x10, not a fixed 0x2510.
        for channel, want in ((0x25, 0x2510), (0x2C, 0x2C10), (0x1E, 0x1E10)):
            primitive = _cop((channel << 24) | 1, 6, (0x456).to_bytes(4, "big") + b"\x22")
            with self.subTest(channel=channel):
                self.assertEqual(struct.unpack_from("<H", primitive, 6)[0], want)

    def test_free_cop_range_cannot_collide_with_receive_cop(self):
        for first in (4, 5):
            cmd, evt = FakeSocket(), FakeSocket()
            with self.subTest(first=first), self.assertRaises(ValueError):
                CaptureReadTransport(cmd, evt, radio_handle=1, receive_cop=5,
                                     first_free_cop=first, request_can_id=0x456,
                                     response_can_id=0x123, keepalive_handle=2,
                                     functional_can_id=0x789)
            self.assertEqual(cmd.sent, [])


if __name__ == "__main__":
    unittest.main()
